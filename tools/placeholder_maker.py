def get_image_size(filepath):
    result = subprocess.run(
        ['sips', '-g', 'pixelWidth', '-g', 'pixelHeight', str(filepath)],
        capture_output=True, text=True, check=True
    )
    width = height = None
    for line in result.stdout.splitlines():
        line = line.strip()
        if line.startswith('pixelWidth:'):
            width = int(line.split()[-1])
        elif line.startswith('pixelHeight:'):
            height = int(line.split()[-1])
    if width is None or height is None:
        raise ValueError(f"Could not determine dimensions of {filepath}")
    return width, height


def measure_text(text, scale):
    return len(text) * 8 * scale, 16 * scale


def draw_text(buf, width, height, text, scale):
    """Render bitmap font text centered on the pixel buffer."""
    text_width, text_height = measure_text(text, scale)
    start_x = max(0, (width - text_width) // 2)
    start_y = max(0, (height - text_height) // 2)

    r_text, g_text, b_text = TEXT_COLOR

    for ci, ch in enumerate(text):
        if ch not in FONT:
            ch = '?'
        glyph = FONT[ch]
        char_x = start_x + ci * 8 * scale

        for row in range(16):
            byte_val = glyph[row]
            for col in range(8):
                if byte_val & (0x80 >> col):
                    for sy in range(scale):
                        for sx in range(scale):
                            px = char_x + col * scale + sx
                            py = start_y + row * scale + sy
                            if 0 <= px < width and 0 <= py < height:
                                i = (py * width + px) * 4
                                buf[i] = r_text
                                buf[i + 1] = g_text
                                buf[i + 2] = b_text
                                buf[i + 3] = 255


def make_placeholder_pixels(width, height, text):
    """Generate RGBA pixel data for a checkerboard placeholder with text."""
    buf = bytearray(width * height * 4)

